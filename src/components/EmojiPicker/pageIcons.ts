/** The curated page-icon set, named in Arabic (`ar`) or English (`en`). */
export function cgPageIcons(language: 'ar' | 'en'): { items: CgEmojiPickerItem[]; groups: CgEmojiPickerGroup[] } {
  return {
    items: ENTRIES.map(([emoji, group, ar, en, keywords]) => ({
      emoji,
      name: language === 'ar' ? ar : en,
      group,
      keywords: [language === 'ar' ? en : ar, ...(keywords?.split(' ') ?? [])],
    })),
    groups: (Object.keys(GROUPS) as GroupKey[]).map((key) => ({ key, label: GROUPS[key][language] })),
  };
}
